namespace LANPartyHub.Server.Domain.Catalog;

/// <summary>
/// The videogame of the catalog of the event (AD-1, AD-22, AD-34).
///
/// <para>
/// The entity carries the eighteen mandatory metadata of FR-1 and it holds the invariants
/// of the domain: a mandatory metadata that is empty is rejected, the range of players has
/// to be coherent, the size is kept in exact bytes and the version is an opaque string of
/// the editor. The rules live here and not in the adapter, so the same rule holds for
/// every way of registering a videogame (AD-1).
/// </para>
/// <para>
/// The identifier is an opaque UUID v7 in its canonical form of thirty-two lowercase
/// hexadecimal digits, and it is generated by the server when the videogame is registered
/// (AD-23).
/// </para>
/// </summary>
public sealed class GameRegistration
{
    /// <summary>
    /// Number of hexadecimal digits of the canonical form of an identifier (AD-23, AD-31).
    /// </summary>
    public const int CanonicalIdentifierLength = 32;

    /// <summary>
    /// Names of the eighteen mandatory metadata of FR-1, in the order of AD-34. The name is
    /// the one that the exception of a missing metadata names, so the organizer knows which
    /// field to fill in (AD-25).
    /// </summary>
    public static class FieldNames
    {
        /// <summary>Opaque UUID v7 identifier of the videogame.</summary>
        public const string GameId = "gameId";

        /// <summary>Human readable name of the videogame.</summary>
        public const string Name = "name";

        /// <summary>Description of the videogame.</summary>
        public const string Description = "description";

        /// <summary>Categories used to filter the catalog.</summary>
        public const string Categories = "categories";

        /// <summary>Free form tags of the videogame.</summary>
        public const string Tags = "tags";

        /// <summary>Reference of the cover image.</summary>
        public const string CoverImage = "coverImage";

        /// <summary>References of the additional images.</summary>
        public const string Images = "images";

        /// <summary>Version published in the catalog.</summary>
        public const string Version = "version";

        /// <summary>Exact size of the package in bytes.</summary>
        public const string SizeBytes = "sizeBytes";

        /// <summary>Minimum number of players.</summary>
        public const string MinPlayers = "minPlayers";

        /// <summary>Maximum number of players.</summary>
        public const string MaxPlayers = "maxPlayers";

        /// <summary>Operating system the videogame runs on.</summary>
        public const string OperatingSystem = "operatingSystem";

        /// <summary>Distribution type of the videogame.</summary>
        public const string DistributionType = "distributionType";

        /// <summary>Installation type of the videogame.</summary>
        public const string InstallationType = "installationType";

        /// <summary>Launch configuration materialized by the signed manifest.</summary>
        public const string LaunchConfiguration = "launchConfiguration";

        /// <summary>Dependencies required by the videogame.</summary>
        public const string Dependencies = "dependencies";

        /// <summary>License of the videogame.</summary>
        public const string License = "license";

        /// <summary>Restrictions on the publication of the videogame.</summary>
        public const string DistributionRestrictions = "distributionRestrictions";
    }

    private readonly string _name;
    private readonly string _description;
    private readonly string[] _categories;
    private readonly string[] _tags;
    private readonly string _coverImage;
    private readonly string[] _images;
    private readonly string _version;
    private readonly string _operatingSystem;
    private readonly string _distributionType;
    private readonly string _installationType;
    private readonly string _launchExecutablePath;
    private readonly string[] _launchArguments;
    private readonly string _launchWorkingDirectory;
    private readonly string[] _dependencies;
    private readonly string _license;
    private readonly string _distributionRestrictions;

    /// <summary>
    /// Creates the registration of a videogame with the eighteen metadata of FR-1.
    /// </summary>
    /// <param name="gameId">Opaque UUID v7 identifier of the videogame.</param>
    /// <param name="name">Human readable name.</param>
    /// <param name="description">Description of the videogame.</param>
    /// <param name="categories">Categories used to filter the catalog.</param>
    /// <param name="tags">Free form tags of the videogame.</param>
    /// <param name="coverImage">Reference of the cover image.</param>
    /// <param name="images">References of the additional images.</param>
    /// <param name="version">Version published in the catalog, as an opaque string.</param>
    /// <param name="sizeBytes">Exact size of the package in bytes.</param>
    /// <param name="minPlayers">Minimum number of players.</param>
    /// <param name="maxPlayers">Maximum number of players.</param>
    /// <param name="operatingSystem">Operating system the videogame runs on.</param>
    /// <param name="distributionType">Distribution type of the videogame.</param>
    /// <param name="installationType">Installation type of the videogame.</param>
    /// <param name="launchExecutablePath">Path of the executable, relative to the install root.</param>
    /// <param name="launchArguments">Arguments passed to the executable.</param>
    /// <param name="launchWorkingDirectory">Working directory of the process.</param>
    /// <param name="dependencies">Dependencies required by the videogame.</param>
    /// <param name="license">License of the videogame.</param>
    /// <param name="distributionRestrictions">Restrictions on the publication of the videogame.</param>
    /// <exception cref="GameMetadataMissingException">A mandatory metadata is empty or absent.</exception>
    /// <exception cref="GamePlayerRangeException">The minimum of players is greater than the maximum.</exception>
    public GameRegistration(
        string gameId,
        string name,
        string description,
        IReadOnlyList<string> categories,
        IReadOnlyList<string> tags,
        string coverImage,
        IReadOnlyList<string> images,
        string version,
        long sizeBytes,
        int minPlayers,
        int maxPlayers,
        string operatingSystem,
        string distributionType,
        string installationType,
        string launchExecutablePath,
        IReadOnlyList<string> launchArguments,
        string launchWorkingDirectory,
        IReadOnlyList<string> dependencies,
        string license,
        string distributionRestrictions)
    {
        ArgumentNullException.ThrowIfNull(categories);
        ArgumentNullException.ThrowIfNull(tags);
        ArgumentNullException.ThrowIfNull(images);
        ArgumentNullException.ThrowIfNull(launchArguments);
        ArgumentNullException.ThrowIfNull(dependencies);

        GameId = RequireIdentifier(gameId);
        _name = RequireText(name, FieldNames.Name);
        _description = RequireText(description, FieldNames.Description);
        _categories = RequireItems(categories, FieldNames.Categories);
        _tags = RequireItems(tags, FieldNames.Tags);
        _coverImage = RequireText(coverImage, FieldNames.CoverImage);
        _images = RequireItems(images, FieldNames.Images);
        _version = RequireText(version, FieldNames.Version);
        _operatingSystem = RequireText(operatingSystem, FieldNames.OperatingSystem);
        _distributionType = RequireText(distributionType, FieldNames.DistributionType);
        _installationType = RequireText(installationType, FieldNames.InstallationType);
        _launchExecutablePath = RequireText(launchExecutablePath, FieldNames.LaunchConfiguration);
        // The launch arguments are optional: a videogame that is launched without
        // arguments is an ordinary case, and FR-1 demands the launch configuration as a
        // whole, not a non-empty list of arguments. The list is trimmed all the same.
        _launchArguments = RequireOptionalItems(launchArguments);
        _launchWorkingDirectory = RequireText(launchWorkingDirectory, FieldNames.LaunchConfiguration);
        _dependencies = RequireItems(dependencies, FieldNames.Dependencies);
        _license = RequireText(license, FieldNames.License);
        _distributionRestrictions = RequireText(distributionRestrictions, FieldNames.DistributionRestrictions);

        if (sizeBytes <= 0)
        {
            throw new GameMetadataMissingException(FieldNames.SizeBytes);
        }

        if (minPlayers <= 0)
        {
            throw new GameMetadataMissingException(FieldNames.MinPlayers);
        }

        if (maxPlayers <= 0)
        {
            throw new GameMetadataMissingException(FieldNames.MaxPlayers);
        }

        if (minPlayers > maxPlayers)
        {
            throw new GamePlayerRangeException(minPlayers, maxPlayers);
        }

        SizeBytes = sizeBytes;
        MinPlayers = minPlayers;
        MaxPlayers = maxPlayers;
    }

    /// <summary>Opaque UUID v7 identifier of the videogame.</summary>
    public string GameId { get; }

    /// <summary>Human readable name.</summary>
    public string Name => _name;

    /// <summary>Description of the videogame.</summary>
    public string Description => _description;

    /// <summary>Categories used to filter the catalog.</summary>
    public IReadOnlyList<string> Categories => _categories;

    /// <summary>Free form tags of the videogame.</summary>
    public IReadOnlyList<string> Tags => _tags;

    /// <summary>Reference of the cover image.</summary>
    public string CoverImage => _coverImage;

    /// <summary>References of the additional images.</summary>
    public IReadOnlyList<string> Images => _images;

    /// <summary>Version published in the catalog, as an opaque string.</summary>
    public string Version => _version;

    /// <summary>Exact size of the package in bytes.</summary>
    public long SizeBytes { get; }

    /// <summary>Minimum number of players.</summary>
    public int MinPlayers { get; }

    /// <summary>Maximum number of players.</summary>
    public int MaxPlayers { get; }

    /// <summary>Operating system the videogame runs on.</summary>
    public string OperatingSystem => _operatingSystem;

    /// <summary>Distribution type of the videogame.</summary>
    public string DistributionType => _distributionType;

    /// <summary>Installation type of the videogame.</summary>
    public string InstallationType => _installationType;

    /// <summary>Path of the executable, relative to the install root.</summary>
    public string LaunchExecutablePath => _launchExecutablePath;

    /// <summary>Arguments passed to the executable.</summary>
    public IReadOnlyList<string> LaunchArguments => _launchArguments;

    /// <summary>Working directory of the process.</summary>
    public string LaunchWorkingDirectory => _launchWorkingDirectory;

    /// <summary>Dependencies required by the videogame.</summary>
    public IReadOnlyList<string> Dependencies => _dependencies;

    /// <summary>License of the videogame.</summary>
    public string License => _license;

    /// <summary>Restrictions on the publication of the videogame.</summary>
    public string DistributionRestrictions => _distributionRestrictions;

    /// <summary>
    /// Generates the identifier of a videogame: an opaque UUID v7 in its canonical form of
    /// thirty-two lowercase hexadecimal digits (AD-23).
    /// </summary>
    /// <returns>The generated identifier.</returns>
    public static string GenerateGameId() => Guid.CreateVersion7().ToString("N");

    /// <summary>
    /// Tells whether a value is the canonical form of an identifier: thirty-two lowercase
    /// hexadecimal digits and nothing else (AD-23, AD-31).
    /// </summary>
    /// <param name="value">Value to check.</param>
    /// <returns><c>true</c> when the value is canonical.</returns>
    public static bool IsCanonicalIdentifier(string? value) =>
        value is { Length: CanonicalIdentifierLength }
        && value.All(character => character is >= '0' and <= '9' or >= 'a' and <= 'f');

    /// <summary>
    /// Requires the identifier of the videogame. An identifier that is absent or that holds
    /// only white space is rejected, and the exception names the identifier itself and not
    /// another field (AD-25).
    /// </summary>
    /// <param name="value">Value of the field.</param>
    /// <returns>The trimmed identifier of the videogame.</returns>
    /// <exception cref="GameMetadataMissingException">The identifier is empty or absent.</exception>
    private static string RequireIdentifier(string? value)
    {
        if (string.IsNullOrWhiteSpace(value))
        {
            throw new GameMetadataMissingException(FieldNames.GameId);
        }

        return value.Trim();
    }

    /// <summary>
    /// Requires a mandatory text. A text that is empty or that holds only white space is
    /// absent, and the exception names the concrete field (AD-25).
    /// </summary>
    /// <param name="value">Value of the field.</param>
    /// <param name="fieldName">Name of the field.</param>
    /// <returns>The trimmed value of the field.</returns>
    /// <exception cref="GameMetadataMissingException">The field is empty or absent.</exception>
    private static string RequireText(string? value, string fieldName)
    {
        if (string.IsNullOrWhiteSpace(value))
        {
            throw new GameMetadataMissingException(fieldName);
        }

        return value.Trim();
    }

    /// <summary>
    /// Requires a mandatory collection. A collection that is empty, that holds an absent
    /// item or that holds an item that is only white space is absent, and the exception
    /// names the concrete field (AD-25). The items that survive are trimmed, the same way
    /// the mandatory texts are (AD-25).
    /// </summary>
    /// <param name="values">Values of the field.</param>
    /// <param name="fieldName">Name of the field.</param>
    /// <returns>The trimmed values of the field.</returns>
    /// <exception cref="GameMetadataMissingException">The collection is empty or holds an absent item.</exception>
    private static string[] RequireItems(IReadOnlyList<string> values, string fieldName)
    {
        if (values.Count == 0)
        {
            throw new GameMetadataMissingException(fieldName);
        }

        var items = new string[values.Count];

        for (var index = 0; index < values.Count; index++)
        {
            var item = values[index];

            if (string.IsNullOrWhiteSpace(item))
            {
                throw new GameMetadataMissingException(fieldName);
            }

            items[index] = item.Trim();
        }

        return items;
    }

    /// <summary>
    /// Requires an optional collection. A collection that is empty is an ordinary value
    /// and it is not an absence, but the items that it holds are trimmed the same way the
    /// mandatory texts are, and an absent item is rejected all the same.
    /// </summary>
    /// <param name="values">Values of the field.</param>
    /// <returns>The trimmed values of the field.</returns>
    /// <exception cref="GameMetadataMissingException">The collection holds an absent item.</exception>
    private static string[] RequireOptionalItems(IReadOnlyList<string> values)
    {
        var items = new string[values.Count];

        for (var index = 0; index < values.Count; index++)
        {
            var item = values[index];

            if (item is null)
            {
                throw new GameMetadataMissingException(FieldNames.LaunchConfiguration);
            }

            items[index] = item.Trim();
        }

        return items;
    }
}
